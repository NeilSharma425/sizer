-- One box per run of land cells in each row, plus a darker rim behind.
local function build(m, shape)
	local rows = shape.rows
	local height = #rows
	local rim = shape.color:Lerp(Color3.new(0, 0, 0), 0.35)
	for r, row in ipairs(rows) do
		local y = height - r + 0.5
		local c = 1
		while c <= #row do
			if row:sub(c, c) == "#" then
				local start = c
				while c <= #row and row:sub(c, c) == "#" do
					c += 1
				end
				local len = c - start
				-- The game camera looks along +Z, so screen-right is -X: flip east/west.
				local x = -(start - 1 + len / 2 - #row / 2)
				Kit.box(m, Vector3.new(len, 1, 1), Vector3.new(x, y, 0), shape.color)
				Kit.box(m, Vector3.new(len + 0.3, 1.3, 0.6), Vector3.new(x, y, 0.4), rim)
			else
				c += 1
			end
		end
	end
	return shape.span
end

return function(builders)
	for name, shape in pairs(SHAPES) do
		builders[name] = function(m)
			return build(m, shape)
		end
	end
end
